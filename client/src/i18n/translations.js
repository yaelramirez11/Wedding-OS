const getNestedValue = (object, path) =>
  path.split(".").reduce((current, key) => current?.[key], object);

export const translate = (language, key) => {
  const value =
    getNestedValue(translations[language], key) ??
    getNestedValue(translations.en, key);

  return value ?? key;
};
